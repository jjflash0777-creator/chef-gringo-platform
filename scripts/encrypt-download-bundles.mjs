// Large chunks on purpose: thousands of small concatenated literals
// overflow the ESLint parser's call stack on the bigger payloads.
const CHUNK = 4096;

function payloadModuleSource(file, payloadBase64) {
  const chunks = [];
  for (let index = 0; index < payloadBase64.length; index += CHUNK) {
    chunks.push(payloadBase64.slice(index, index + CHUNK));
  }
  const body = chunks.map((chunk) => `  "${chunk}",`).join("\n");
  return `// GENERATED by scripts/encrypt-download-bundles.mjs — do not edit by hand.
// AES-256-GCM ciphertext (base64 of IV || ciphertext || tag) for
// ${file.key}. Plaintext is recoverable only with the DOWNLOAD_BUNDLE_KEY
// server env var; see app/lib/download-bundles/decrypt.ts.
export const PAYLOAD: string = [
${body}
].join("");
`;
}

function manifestSource(files) {
  const imports = files
    .map((file) => `import { PAYLOAD as ${file.alias} } from "./payloads/${file.module}.ts";`)
    .join("\n");
  const entries = files
    .map(
      (file) =>
        `  "${file.key}": {\n    payload: ${file.alias},\n    contentType: "${file.contentType}",\n    fileName: "${file.fileName}",\n  },`,
    )
    .join("\n");
  return `// GENERATED by scripts/encrypt-download-bundles.mjs — do not edit by hand.
// Maps each catalog file key (app/lib/downloads.ts) to its encrypted
// payload module, content type, and download filename. The downloads
// test suite asserts these entries match the catalog exactly.
${imports}

export type DownloadBundleEntry = {
  /** Base64 AES-256-GCM payload: IV || ciphertext || tag. */
  payload: string;
  contentType: string;
  fileName: string;
};

export const DOWNLOAD_BUNDLES: Readonly<Record<string, DownloadBundleEntry>> = {
${entries}
};
`;
}

async function main() {
  const sourceDir = process.argv[2];
  if (!sourceDir) {
    console.error("Usage: DOWNLOAD_BUNDLE_KEY=<base64 key> node scripts/encrypt-download-bundles.mjs <plaintext-dir>");
    process.exit(1);
  }
  const keyBase64 = process.env.DOWNLOAD_BUNDLE_KEY ?? "";
  const key = Buffer.from(keyBase64, "base64");
  if (!keyBase64 || key.length !== 32) {
    console.error(
      `Refusing to run: DOWNLOAD_BUNDLE_KEY must be a base64-encoded 32-byte key (decoded ${key.length} bytes).`,
    );
    process.exit(1);
  }

  const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const payloadsDir = path.join(repoRoot, "app/lib/download-bundles/payloads");
  await mkdir(payloadsDir, { recursive: true });

  for (const file of FILES) {
    const plaintext = await readFile(path.join(sourceDir, file.source));
    const iv = randomBytes(12);
    const cipher = createCipheriv("aes-256-gcm", key, iv);
    const ciphertext = Buffer.concat([cipher.update(plaintext), cipher.final()]);
    const payload = Buffer.concat([iv, ciphertext, cipher.getAuthTag()]).toString("base64");
    await writeFile(path.join(payloadsDir, `${file.module}.ts`), payloadModuleSource(file, payload));
    console.log(`encrypted ${file.source} (${plaintext.length} bytes) -> payloads/${file.module}.ts`);
  }
  await writeFile(path.join(repoRoot, "app/lib/download-bundles/manifest.ts"), manifestSource(FILES));
  console.log("wrote app/lib/download-bundles/manifest.ts");
}

await main();
