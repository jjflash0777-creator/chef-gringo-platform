#!/usr/bin/env node
/**
 * Regenerate the encrypted /downloads bundles from plaintext sources.
 *
 * Usage:
 *   DOWNLOAD_BUNDLE_KEY=<base64 32-byte key> node scripts/encrypt-download-bundles.mjs <plaintext-dir>
 *
 * <plaintext-dir> holds the six list-ready product files under their
 * plain filenames (kitchen-reference-chart-set.pdf, ...). The script
 * encrypts each file with AES-256-GCM (random 12-byte IV per file;
 * stored payload is base64 of IV || ciphertext || GCM tag) and rewrites:
 *
 *   app/lib/download-bundles/payloads/<module>.ts   (one per file)
 *   app/lib/download-bundles/manifest.ts            (key -> payload map)
 *
 * The FILES table below mirrors app/lib/downloads.ts; the downloads
 * test suite asserts the manifest keys, content types, and filenames
 * match the catalog exactly, so drift fails loudly. The key comes only
 * from the DOWNLOAD_BUNDLE_KEY env var and is never written to disk by
 * this script. Generate one with: openssl rand -base64 32
 * The same value must be set as DOWNLOAD_BUNDLE_KEY in the production
 * Sites env, or delivery fails closed.
 */
import { createCipheriv, randomBytes } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

